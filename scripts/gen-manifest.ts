/**
 * Scans src/tools/*, src/data/templates/* and src/data/templates/pandaqi/*, then
 * writes the tool registry, a Svelte-free schema map for the linter, the template
 * summaries the lists render and the template texts behind a dynamic import.
 * `--check` fails when stale.
 */

import { existsSync, readFileSync, readdirSync, unlinkSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { startLanguage } from '../src/core/i18n';
import type { summariseTemplate } from '../src/data/template-summary';

const root = join(import.meta.dir, '..');
const checkOnly = process.argv.includes('--check');

// Template summaries read the parser, which reads its words through the language
// layer, so the generator loads one the way the app does.
await startLanguage('en');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')) as { version: string };

interface ToolEntry {
  id: string;
  varName: string;
  metaVar: string;
  title: string;
}

const toolsDir = join(root, 'src', 'tools');
const dirs = readdirSync(toolsDir, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();

const entries: ToolEntry[] = [];
for (const dir of dirs) {
  const base = join(toolsDir, dir);
  const required = ['meta.ts', 'preset.ts', 'tool.svelte.ts'];
  if (!required.every((file) => existsSync(join(base, file)))) continue;
  const mod = await import(pathToFileURL(join(base, 'meta.ts')).href);
  const meta = mod.default as { id?: string; title?: string } | undefined;
  if (!meta?.id) {
    console.error(`[gen] ${dir}/meta.ts has no default export with an id`);
    process.exit(1);
  }
  if (meta.id !== dir) {
    console.error(`[gen] ${dir}/meta.ts id "${meta.id}" must match its folder name`);
    process.exit(1);
  }
  const suffix = meta.id.replace(/[^a-z0-9]/gi, '_');
  entries.push({ id: meta.id, varName: `tool_${suffix}`, metaVar: `meta_${suffix}`, title: meta.title ?? meta.id });
}

// Metadata only: the home screen must not pull a single tool's code in.
const manifestLines: string[] = [
  '// Generated by scripts/gen-manifest.ts. Do not edit by hand.',
  '// Run `bun run gen` after adding, removing or renaming a tool folder.',
  "import type { ToolMeta } from './registry';",
  ...entries.map((entry) => `import ${entry.metaVar} from '../tools/${entry.id}/meta.ts';`),
  '',
  `export const manifest: ToolMeta[] = [${entries.map((entry) => entry.metaVar).join(', ')}];`,
  '',
  '',
];

// One dynamic import per tool: a tool's folder is its own chunk, fetched on use.
const loaderLines: string[] = [
  '// Generated by scripts/gen-manifest.ts. Do not edit by hand.',
  '// Each tool is a chunk of its own. Nothing here runs until a session needs it.',
  "import type { AnyToolModule } from './registry';",
  '',
  'const loaders: Record<string, () => Promise<AnyToolModule>> = {',
  ...entries.map(
    (entry) => `  ${entry.id}: () => import('../tools/${entry.id}/tool.svelte.ts').then((module) => module.default),`,
  ),
  '};',
  '',
  'export function hasTool(id: string): boolean {',
  '  return Object.prototype.hasOwnProperty.call(loaders, id);',
  '}',
  '',
  '/** Loads one tool on demand. Rejects for an id this build does not ship. */',
  'export function loadTool(id: string): Promise<AnyToolModule> {',
  '  const load = loaders[id];',
  '  return load ? load() : Promise.reject(new Error(`Unknown tool "${id}"`));',
  '}',
  '',
];

const schemaLines: string[] = [
  '// Generated by scripts/gen-manifest.ts. Do not edit by hand.',
  '// Svelte-free: used by the template linter, scripts and tests.',
  "import type { PresetSchema } from './template/schema';",
  ...entries.map((entry) => `import ${entry.varName}Preset from '../tools/${entry.id}/preset.ts';`),
  '',
  'export const schemas: Record<string, PresetSchema> = {',
  ...entries.map((entry) => `  ${entry.id}: ${entry.varName}Preset,`),
  '};',
  '',
];

// Parsing happens here, once, so the running app never has to.
const { summariseTemplate: summarise } = (await import(
  pathToFileURL(join(root, 'src', 'data', 'template-summary.ts')).href
)) as { summariseTemplate: typeof summariseTemplate };

const templatesDir = join(root, 'src', 'data', 'templates');
const pandaqiDir = join(templatesDir, 'pandaqi');

function readTemplates(dir: string) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((file) => file.endsWith('.gamebuddy'))
    .sort()
    .map((file) => {
      const text = readFileSync(join(dir, file), 'utf8');
      const id = file.replace(/\.gamebuddy$/, '');
      return { id, text, summary: summarise(id, text) };
    });
}

const templates = readTemplates(templatesDir);
const pandaqi = readTemplates(pandaqiDir);
// First-party Pandaqi games keep their own folder but ship with the bundled set:
// one gallery, one list, one Pandaqi filter. The tag is checked by the linter.
const bundled = [...templates, ...pandaqi];
const bundledIds = new Set<string>();
for (const item of bundled) {
  if (bundledIds.has(item.id)) {
    console.error(`[gen] duplicate template id "${item.id}"`);
    process.exit(1);
  }
  bundledIds.add(item.id);
}

// A template's mark lives beside it as `<id>.icon.svg`; several templates may
// name the same mark with `icon:`, so the map carries both the id and the name.
const iconMap: Record<string, string> = {};
for (const [dir, items] of [
  [templatesDir, templates],
  [pandaqiDir, pandaqi],
] as const) {
  for (const item of items) {
    const iconPath = join(dir, `${item.id}.icon.svg`);
    if (!existsSync(iconPath)) continue;
    const svg = readFileSync(iconPath, 'utf8').trim();
    if (!svg.startsWith('<svg')) continue;
    // Index by the name a template asks for; the id is the fallback for a file
    // with no `icon:` line at all.
    const name = item.text.match(/^icon:\s*(\S+)/m)?.[1];
    iconMap[name || item.id] = svg;
  }
}

// Community files arrive by pull request in src/data/community. They are compiled
// in like the rest, so nothing is fetched when a player opens one.
const communityDir = join(root, 'src', 'data', 'community');
const communityFiles = existsSync(communityDir)
  ? readdirSync(communityDir)
      .filter((file) => file.endsWith('.gamebuddy'))
      .sort()
  : [];
const community = communityFiles.map((file) => {
  const text = readFileSync(join(communityDir, file), 'utf8');
  const id = `community-${file.replace(/\.gamebuddy$/, '')}`;
  const summary = summarise(id, text);
  if (!summary.tags.includes('community')) summary.tags = [...summary.tags, 'community'];
  return { id, text, summary };
});

// Community submissions may ship a mark the same way: <file>.icon.svg beside
// the template in src/data/community, indexed under its id and icon name.
for (const item of community) {
  const base = item.id.replace(/^community-/, '');
  const iconPath = join(communityDir, `${base}.icon.svg`);
  if (!existsSync(iconPath)) continue;
  const svg = readFileSync(iconPath, 'utf8').trim();
  if (!svg.startsWith('<svg')) continue;
  const name = item.text.match(/^icon:\s*(\S+)/m)?.[1];
  iconMap[name || item.id] = svg;
}

const iconLines: string[] = [
  '// Generated by scripts/gen-manifest.ts. Do not edit by hand.',
  '// Marks live next to their template as <id>.icon.svg; this map is the lazy chunk.',
  'export const templateIcons: Record<string, string> = ',
  `${JSON.stringify(iconMap, null, 2)};`,
  '',
];

const summaryLines: string[] = [
  '// Generated by scripts/gen-manifest.ts. Do not edit by hand.',
  '// Names, player counts and tools: the gallery without a single template text.',
  "import type { TemplateSummary } from './template-summary';",
  '',
  'export const bundledTemplates: TemplateSummary[] = [',
  ...bundled.map((item) => `  ${JSON.stringify(item.summary)},`),
  '];',
  '',
  '/** Templates contributed through src/data/community, compiled in at build time. */',
  'export const communityTemplates: TemplateSummary[] = [',
  ...community.map((item) => `  ${JSON.stringify(item.summary)},`),
  '];',
  '',
];

const textLines: string[] = [
  '// Generated by scripts/gen-manifest.ts. Do not edit by hand.',
  '// Compiled in as strings, but only behind a dynamic import: never fetched, and',
  '// never part of the first visit.',
  'export const templateTexts: { id: string; text: string }[] = [',
  ...[...bundled, ...community].map(
    (item) => `  { id: ${JSON.stringify(item.id)}, text: ${JSON.stringify(item.text)} },`,
  ),
  '];',
  '',
];

// --- languages ------------------------------------------------------------
// Every core dictionary, English included, is a chunk of its own: no language is
// compiled into the start-up. A tool keeps its translations beside it in
// `locales/<lang>.ts`; those are gathered into one file per language, so picking
// a language costs one fetch instead of one per tool.
const LOCALE_FILE = /^([a-z]{2})\.ts$/;
const coreLocalesDir = join(root, 'src', 'core', 'locales');
const coreLocaleIds = existsSync(coreLocalesDir)
  ? readdirSync(coreLocalesDir)
      .map((file) => file.match(LOCALE_FILE)?.[1] ?? '')
      .filter((id) => id !== '')
      .sort()
  : [];

const toolText: Record<string, Record<string, string>> = {};
for (const dir of dirs) {
  const localeDir = join(toolsDir, dir, 'locales');
  if (!existsSync(localeDir)) continue;
  for (const file of readdirSync(localeDir).sort()) {
    const languageId = file.match(LOCALE_FILE)?.[1];
    if (!languageId) continue;
    const module = (await import(pathToFileURL(join(localeDir, file)).href)) as {
      default?: Record<string, unknown>;
    };
    const dict = module.default;
    if (!dict || typeof dict !== 'object') {
      console.error(`[gen] ${dir}/locales/${file} must default-export an object of strings`);
      process.exit(1);
    }
    const bucket = (toolText[languageId] ??= {});
    for (const [key, value] of Object.entries(dict)) {
      if (typeof value !== 'string') {
        console.error(`[gen] ${dir}/locales/${file}: "${key}" is not a string`);
        process.exit(1);
      }
      const namespaced = `${dir}.${key}`;
      if (namespaced in bucket) {
        console.error(`[gen] two tools both claim the key "${namespaced}"`);
        process.exit(1);
      }
      bucket[namespaced] = value;
    }
  }
}

// English tool words are not gathered: each tool registers its own, so they ride
// in its chunk and a language nobody picked never carries them twice.
const toolTextIds = Object.keys(toolText)
  .filter((id) => id !== 'en')
  .sort();

const registryLines: string[] = [
  '// Generated by scripts/gen-manifest.ts. Do not edit by hand.',
  '// Every language is a chunk of its own, loaded on boot and on switch.',
  "import type { Dict } from '../i18n.svelte';",
  '',
  'export const coreLocaleLoaders: Record<string, () => Promise<{ default: Dict }>> = {',
  ...coreLocaleIds.map((id) => `  ${id}: () => import('./${id}'),`),
  '};',
  '',
  'export const toolTextLoaders: Record<string, () => Promise<{ default: Dict }>> = {',
  ...toolTextIds.map((id) => `  ${id}: () => import('./tool-text-${id}.generated'),`),
  '};',
  '',
];

const versionLines: string[] = [
  '// Generated by scripts/gen-manifest.ts from package.json. Do not edit by hand.',
  '// Semantic versioning: package.json is the only place the number is written.',
  `export const VERSION = ${JSON.stringify(pkg.version)};`,
  '',
];

const outputs: { path: string; content: string }[] = [
  { path: join(root, 'src', 'core', 'version.generated.ts'), content: versionLines.join('\n') },
  { path: join(root, 'src', 'core', 'manifest.generated.ts'), content: manifestLines.join('\n') },
  { path: join(root, 'src', 'core', 'tools.generated.ts'), content: loaderLines.join('\n') },
  { path: join(root, 'src', 'core', 'schemas.generated.ts'), content: schemaLines.join('\n') },
  { path: join(root, 'src', 'data', 'templates.generated.ts'), content: summaryLines.join('\n') },
  { path: join(root, 'src', 'data', 'template-text.generated.ts'), content: textLines.join('\n') },
  { path: join(root, 'src', 'data', 'template-icons.generated.ts'), content: iconLines.join('\n') },
  { path: join(coreLocalesDir, 'registry.generated.ts'), content: registryLines.join('\n') },
];

for (const id of toolTextIds) {
  const keys = Object.keys(toolText[id]).sort();
  const lines = [
    '// Generated by scripts/gen-manifest.ts. Do not edit by hand.',
    `// Every tool's ${id} words, gathered so a language switch is one fetch.`,
    'export default {',
    ...keys.map((key) => `  ${JSON.stringify(key)}: ${JSON.stringify(toolText[id][key])},`),
    '};',
    '',
  ];
  outputs.push({ path: join(coreLocalesDir, `tool-text-${id}.generated.ts`), content: lines.join('\n') });
}

// A language that was removed leaves its generated file behind; drop it.
if (!checkOnly && existsSync(coreLocalesDir)) {
  for (const file of readdirSync(coreLocalesDir)) {
    const match = file.match(/^tool-text-([a-z]{2})\.generated\.ts$/);
    if (match && !toolTextIds.includes(match[1])) unlinkSync(join(coreLocalesDir, file));
  }
}

let stale = false;
for (const output of outputs) {
  const current = existsSync(output.path) ? readFileSync(output.path, 'utf8') : '';
  if (current !== output.content) {
    stale = true;
    if (!checkOnly) writeFileSync(output.path, output.content);
  }
}

if (checkOnly && stale) {
  console.error('[gen] generated files are stale. Run `bun run gen`.');
  process.exit(1);
}

console.log(
  `[gen] ${entries.length} tools, ${bundled.length} templates, ${Object.keys(iconMap).length} marks, ${coreLocaleIds.length} languages${checkOnly ? ' (up to date)' : ''}`,
);
