/**
 * Scans src/tools/*, writes the registry manifest, a Svelte-free schema map for
 * the linter and the bundled template list. `--check` fails when output is stale.
 */

import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

const root = join(import.meta.dir, '..');
const checkOnly = process.argv.includes('--check');

interface ToolEntry {
  id: string;
  varName: string;
  title: string;
}

const toolsDir = join(root, 'src', 'tools');
const dirs = readdirSync(toolsDir, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();

const entries: ToolEntry[] = [];
for (const dir of dirs) {
  const base = join(toolsDir, dir);
  const required = ['meta.ts', 'preset.ts', 'tool.svelte.ts'];
  if (!required.every((file) => existsSync(join(base, file)))) continue;
  const mod = await import(pathToFileURL(join(base, 'meta.ts')).href);
  const meta = mod.default as { id?: string; title?: string } | undefined;
  if (!meta?.id) {
    console.error(`[gen] ${dir}/meta.ts has no default export with an id`);
    process.exit(1);
  }
  if (meta.id !== dir) {
    console.error(`[gen] ${dir}/meta.ts id "${meta.id}" must match its folder name`);
    process.exit(1);
  }
  entries.push({ id: meta.id, varName: `tool_${meta.id.replace(/[^a-z0-9]/gi, '_')}`, title: meta.title ?? meta.id });
}

const manifestLines: string[] = [
  '// Generated by scripts/gen-manifest.ts. Do not edit by hand.',
  '// Run `bun run gen` after adding, removing or renaming a tool folder.',
  "import type { AnyToolModule } from './registry';",
  ...entries.map((entry) => `import ${entry.varName} from '../tools/${entry.id}/tool.svelte.ts';`),
  '',
  `export const manifest: AnyToolModule[] = [${entries.map((entry) => entry.varName).join(', ')}];`,
  '',
];

const schemaLines: string[] = [
  '// Generated by scripts/gen-manifest.ts. Do not edit by hand.',
  '// Svelte-free: used by the template linter, scripts and tests.',
  "import type { PresetSchema } from './template/schema';",
  ...entries.map((entry) => `import ${entry.varName}Preset from '../tools/${entry.id}/preset.ts';`),
  '',
  'export const schemas: Record<string, PresetSchema> = {',
  ...entries.map((entry) => `  ${entry.id}: ${entry.varName}Preset,`),
  '};',
  '',
];

const templatesDir = join(root, 'src', 'data', 'templates');
const templateFiles = existsSync(templatesDir)
  ? readdirSync(templatesDir)
      .filter((file) => file.endsWith('.gamebuddy'))
      .sort()
  : [];

const templateLines: string[] = [
  '// Generated by scripts/gen-manifest.ts. Do not edit by hand.',
  '// Templates are compiled in as strings: never fetched.',
  'export const bundledTemplates: { id: string; text: string }[] = [',
  ...templateFiles.map((file) => {
    const text = readFileSync(join(templatesDir, file), 'utf8');
    const id = file.replace(/\.gamebuddy$/, '');
    return `  { id: ${JSON.stringify(id)}, text: ${JSON.stringify(text)} },`;
  }),
  '];',
  '',
];

const outputs: { path: string; content: string }[] = [
  { path: join(root, 'src', 'core', 'manifest.generated.ts'), content: manifestLines.join('\n') },
  { path: join(root, 'src', 'core', 'schemas.generated.ts'), content: schemaLines.join('\n') },
  { path: join(root, 'src', 'data', 'templates.generated.ts'), content: templateLines.join('\n') },
];

let stale = false;
for (const output of outputs) {
  const current = existsSync(output.path) ? readFileSync(output.path, 'utf8') : '';
  if (current !== output.content) {
    stale = true;
    if (!checkOnly) writeFileSync(output.path, output.content);
  }
}

if (checkOnly && stale) {
  console.error('[gen] generated files are stale. Run `bun run gen`.');
  process.exit(1);
}

console.log(`[gen] ${entries.length} tools, ${templateFiles.length} templates${checkOnly ? ' (up to date)' : ''}`);
