/** State and settings back to clean, commented template text. */

import type { PresetSchema, PresetValues, FieldSpec } from './schema';
import { formatDurationText } from './schema';

export interface TemplateSpec {
  game: {
    name: string;
    players?: string;
    time?: string;
    tags?: string[];
    source?: string;
    author?: string;
    license?: string;
    format?: number;
  };
  players: string[];
  tools: { toolId: string; instanceId: string; values: PresetValues }[];
  setup?: string[];
  rules?: string;
  notes?: string;
}

function formatValue(spec: FieldSpec | undefined, value: unknown): string {
  if (value === null || value === undefined) return '';
  if (spec?.type === 'duration') return formatDurationText(Number(value));
  if (spec?.type === 'boolean') return value ? 'yes' : 'no';
  if (spec?.type === 'list') {
    const items = Array.isArray(value) ? value.map(String) : [];
    return items.map((item) => (item.includes(',') ? `"${item}"` : item)).join(', ');
  }
  if (spec?.type === 'pairs') {
    const entries = Object.entries(value as Record<string, string | number>);
    return entries.map(([key, val]) => `${key}=${val}`).join(', ');
  }
  if (typeof value === 'boolean') return value ? 'yes' : 'no';
  if (typeof value === 'number') return String(value);
  if (Array.isArray(value)) return value.map(String).join(', ');
  if (typeof value === 'object') {
    return Object.entries(value as Record<string, unknown>)
      .map(([key, val]) => `${key}=${String(val)}`)
      .join(', ');
  }
  const text = String(value);
  if (/^[\s"]|[\s"]$|,\s|\n/.test(text)) return `"${text.replace(/"/g, "'")}"`;
  return text;
}

function sectionKey(toolId: string, instanceId: string): string {
  return instanceId && instanceId !== toolId ? `[tool ${toolId} ${instanceId}]` : `[tool ${toolId}]`;
}

/** Deterministic text output: same input, same file. Diff-friendly. */
export function serializeTemplate(spec: TemplateSpec, schemaOf?: (toolId: string) => PresetSchema | undefined): string {
  const out: string[] = [];
  out.push(`# ${spec.game.name} — generated by Game Buddy`);
  out.push('');
  out.push('[game]');
  out.push(`name: ${formatValue(undefined, spec.game.name)}`);
  if (spec.game.players) out.push(`players: ${spec.game.players}`);
  if (spec.game.time) out.push(`time: ${spec.game.time}`);
  if (spec.game.tags?.length) out.push(`tags: ${spec.game.tags.join(', ')}`);
  if (spec.game.source) out.push(`source: ${spec.game.source}`);
  if (spec.game.author) out.push(`author: ${spec.game.author}`);
  if (spec.game.license) out.push(`license: ${spec.game.license}`);
  out.push(`format: ${spec.game.format ?? 1}`);

  if (spec.players.length) {
    out.push('');
    out.push('[players]');
    for (const player of spec.players) out.push(player);
  }

  for (const tool of spec.tools) {
    const schema = schemaOf?.(tool.toolId);
    out.push('');
    out.push(sectionKey(tool.toolId, tool.instanceId));
    const keys = schema ? Object.keys(schema) : Object.keys(tool.values);
    for (const key of keys) {
      if (tool.values[key] === undefined) continue;
      const spec2 = schema?.[key];
      const value = tool.values[key];
      // Multi-line text uses the block form so newlines survive a re-parse.
      if (spec2?.type === 'text' && typeof value === 'string' && value.includes('\n')) {
        out.push(`${key}: |`);
        for (const line of value.split('\n')) out.push(`  ${line}`);
        continue;
      }
      const text = formatValue(spec2, value);
      if (text === '') continue;
      out.push(`${key}: ${text}`);
    }
    for (const key of Object.keys(tool.values)) {
      if (schema && key in schema) continue;
      const text = formatValue(undefined, tool.values[key]);
      if (text === '') continue;
      out.push(`${key}: ${text}`);
    }
  }

  if (spec.setup?.length) {
    out.push('');
    out.push('[setup]');
    for (const item of spec.setup) out.push(`- ${item}`);
  }

  if (spec.rules?.trim()) {
    out.push('');
    out.push('[rules]');
    out.push(spec.rules.trim());
  }

  if (spec.notes?.trim()) {
    out.push('');
    out.push('[notes]');
    out.push(spec.notes.trim());
  }

  out.push('');
  return out.join('\n');
}

export function suggestFilename(name: string): string {
  const slug = name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
  return `${slug || 'game'}.gamebuddy`;
}
